/// Önizleme haritasında sahneye sığdırılacak bölge (derece) ve kenar
/// boşlukları. Bölgenin merkezi, boşluklar çıkarıldıktan sonra kalan alanın
/// ortasına gelir; paneller altta duruyorsa alt boşluk büyük tutulur.
struct PreviewMapFocus: Equatable {
    var west: Double
    var east: Double
    var south: Double
    var north: Double
    var insets = EdgeInsets(top: 22, leading: 12, bottom: 42, trailing: 12)

    /// Türkiye'nin tamamı (harita önizlemesi).
    static let turkey = PreviewMapFocus(west: 25.6, east: 44.9, south: 35.8, north: 42.2)
}

/// Önizleme haritasının izdüşümü: harita ekranıyla aynı (Web Mercator), bu
/// yüzden kıyılar ve fay hatları uygulamadaki gibi görünür. Odak bölgesi
/// sahneye sığdırılır; genişlik arttıkça (iPad) çevre de görünür.
struct PreviewMapProjection {
    /// Radyan başına nokta.
    private let scale: Double
    private let centerX: Double
    private let centerY: Double
    private let origin: CGPoint

    init(size: CGSize, focus: PreviewMapFocus = .turkey) {
        let insets = focus.insets
        let width = Double(size.width - insets.leading - insets.trailing)
        let height = Double(size.height - insets.top - insets.bottom)
        let spanX = (focus.east - focus.west) * .pi / 180
        let spanY = Self.mercatorY(focus.north) - Self.mercatorY(focus.south)
        scale = max(1, min(width / spanX, height / spanY))
        centerX = (focus.west + focus.east) / 2 * .pi / 180
        centerY = (Self.mercatorY(focus.north) + Self.mercatorY(focus.south)) / 2
        origin = CGPoint(x: insets.leading + CGFloat(width) / 2, y: insets.top + CGFloat(height) / 2)
    }

    func point(latitude: Double, longitude: Double) -> CGPoint {
        CGPoint(x: origin.x + (longitude * .pi / 180 - centerX) * scale,
                y: origin.y - (Self.mercatorY(latitude) - centerY) * scale)
    }

    func point(_ coordinate: SIMD2<Double>) -> CGPoint {
        point(latitude: coordinate.y, longitude: coordinate.x)
    }

    /// Verilen enlemde `km` uzunluğun ekrandaki karşılığı (Mercator'da doğu ve
    /// kuzey yönünde aynı; daireler daire kalır).
    func length(km: Double, atLatitude latitude: Double) -> CGFloat {
        km / 6371 * scale / cos(latitude * .pi / 180)
    }

    private static func mercatorY(_ latitude: Double) -> Double {
        log(tan(.pi / 4 + latitude * .pi / 360))
    }
}

/// Harita zemini: deniz, kara, ülke sınırları ve büyük göller. Odak sabit
/// olduğundan boyut veya görünüm (açık/koyu) değişmedikçe yeniden çizilmez.
struct PreviewRegionMapLayer: View {
    var focus: PreviewMapFocus = .turkey

    private static let sea = Color(uiColor: UIColor { trait in
        trait.userInterfaceStyle == .dark
            ? UIColor(red: 0.11, green: 0.16, blue: 0.23, alpha: 1)
            : UIColor(red: 0.67, green: 0.81, blue: 0.93, alpha: 1)
    })
    private static let land = Color(uiColor: UIColor { trait in
        trait.userInterfaceStyle == .dark
            ? UIColor(red: 0.21, green: 0.22, blue: 0.23, alpha: 1)
            : UIColor(red: 0.96, green: 0.95, blue: 0.92, alpha: 1)
    })
    private static let border = Color(uiColor: UIColor { trait in
        trait.userInterfaceStyle == .dark
            ? UIColor(red: 0.37, green: 0.38, blue: 0.40, alpha: 1)
            : UIColor(red: 0.76, green: 0.74, blue: 0.71, alpha: 1)
    })

    var body: some View {
        Canvas { context, size in
            let projection = PreviewMapProjection(size: size, focus: focus)
            context.fill(Path(CGRect(origin: .zero, size: size)), with: .color(Self.sea))

            let land = Self.path(PreviewRegionMap.countries, projection)
            context.fill(land, with: .color(Self.land))
            context.fill(Self.path(PreviewRegionMap.lakes, projection), with: .color(Self.sea))
            // Tek çizgi hem kıyıyı hem sınırları keskinleştirir; ortak sınırlar
            // iki kez çizilse de renk opak olduğu için koyulaşmaz.
            context.stroke(land, with: .color(Self.border),
                           style: StrokeStyle(lineWidth: 0.6, lineCap: .round, lineJoin: .round))
        }
    }

    private static func path(_ rings: [[SIMD2<Double>]], _ projection: PreviewMapProjection) -> Path {
        var path = Path()
        for ring in rings where ring.count > 2 {
            path.addLines(ring.map(projection.point))
            path.closeSubpath()
        }
        return path
    }
}
